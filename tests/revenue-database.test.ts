import test from "node:test";
import assert from "node:assert/strict";
import { readdir, readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { createWorkspace } from "../src/lib/demo";
import { cloudState, migrateState } from "../src/lib/storage";
import { latestRevenue, revenueSummary, type RevenueData, type RevenueValues } from "../src/lib/revenue";

for (const withPrivateNotes of [false, true]) test(`revenue database: values, order, retries, isolation, permissions (private notes ${withPrivateNotes})`, async () => {
  const db = await PGlite.create();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb not null default '{}');
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema public,auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;`);
    for (const name of (await readdir("supabase/migrations")).filter(n => n.endsWith(".sql") && (withPrivateNotes || !n.includes("planner_private_notes"))).sort()) await db.exec(await readFile(`supabase/migrations/${name}`, "utf8"));
    const users = [41, 42, 43].map(n => `00000000-0000-0000-0000-${String(n).padStart(12, "0")}`);
    for (const id of users) await db.query("insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data) values($1,$2,now(),'{\"company_name\":\"Revenue test\"}')", [id, `${id}@example.test`]);
    const members = (await db.query<{ user_id: string; company_id: string }>("select user_id,company_id from memberships")).rows;
    const companies = users.map(u => members.find(m => m.user_id === u)!.company_id), company = companies[0];
    const signIn = async (u: string) => { await db.exec("set role authenticated"); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [u]); };
    const read = async (tenant = company) => (await db.query<{ d: RevenueData }>("select read_revenue($1) d", [tenant])).rows[0].d;
    const save = async (id: string, version: number | null, values: unknown, tenant = company) => (await db.query<{ d: RevenueData }>("select save_revenue($1,$2,$3,$4::jsonb) d", [tenant, id, version, JSON.stringify(values)])).rows[0].d;
    const values: RevenueValues = { date: "2026-11-21", shift: "", cash: 10, cards: null };
    const ids = [crypto.randomUUID(), crypto.randomUUID(), crypto.randomUUID()];
    await signIn(users[0]);
    await assert.rejects(read(), /MODULE_DISABLED/); await assert.rejects(save(ids[0], null, values), /MODULE_DISABLED/);
    await db.query("select set_company_module($1,'revenue',true)", [company]);
    await db.query("select save_workspace_v2($1,$2::jsonb,0,$3)", [company, JSON.stringify(cloudState(migrateState({ schema: 2, revision: 1, current: createWorkspace("Revenue test"), past: [], future: [] }))), crypto.randomUUID()]);
    assert.deepEqual(await read(), { entries: [] }); assert.equal(latestRevenue(await read()), null);
    const workspaceBefore = (await db.query("select state,version from workspace_documents where company_id=$1", [company])).rows;
    let data = await save(ids[0], null, values);
    assert.equal(data.entries[0].cash, 10); assert.equal(data.entries[0].cards, null);
    const retries = await Promise.all([save(ids[0], null, values), save(ids[0], null, values)]);
    assert.deepEqual(retries[0], retries[1]); assert.equal(retries[0].entries.length, 1);
    data = await save(ids[1], null, { ...values, shift: "Veče", cash: null, cards: 20 });
    assert.deepEqual(latestRevenue(data), { id: ids[1], date: values.date, total: 20 });
    assert.equal(revenueSummary(data).total, 30);
    data = await save(ids[2], null, { ...values, date: "2026-11-01", cash: 1025, cards: 2050 });
    assert.deepEqual(latestRevenue(data), { id: ids[2], date: "2026-11-01", total: 3075 });
    assert.equal(revenueSummary(data).total, 3105);
    const original = data.entries.find(e => e.id === ids[0])!;
    data = await save(ids[0], 0, { ...values, date: "2026-10-31", cash: 0 });
    const edited = data.entries.find(e => e.id === ids[0])!;
    assert.equal(edited.createdAt, original.createdAt); assert.equal(edited.sequence, original.sequence); assert.equal(edited.version, 1);
    assert.equal(edited.cash, 0); assert.equal(edited.cards, null); assert.equal(latestRevenue(data)?.id, ids[2]);
    assert.deepEqual(await read(), data, "refresh retains exact values and creation order");
    await assert.rejects(save(ids[0], 0, values), /VERSION_CONFLICT/);
    await assert.rejects(save(ids[0], null, values), /VERSION_CONFLICT/);
    await assert.rejects(save(crypto.randomUUID(), 0, values), /VERSION_CONFLICT/);
    const beforeInvalid = await read();
    for (const invalid of [null, [], {}, { ...values, cash: null }, { ...values, cash: -1 }, { ...values, cash: 1.5 }, { ...values, cash: 100000000000 }, { ...values, cash: "10" }, { ...values, cards: false }, { ...values, date: "2026-02-29" }, { ...values, date: "2026-11-21T00:00:00Z" }, { ...values, date: "0000-01-01" }, { ...values, shift: "x".repeat(81) }, { ...values, createdAt: "2030-01-01" }]) await assert.rejects(save(crypto.randomUUID(), null, invalid));
    assert.deepEqual(await read(), beforeInvalid, "all invalid writes roll back");
    assert.equal(data.entries.length, 3); assert.ok(!data.entries.some(e => e.date === "2026-11-20"), "no zero rows for missing dates");
    assert.deepEqual((await db.query("select state,version from workspace_documents where company_id=$1", [company])).rows, workspaceBefore, "financial writes do not change planner document");
    await db.query("select set_company_module($1,'revenue',false)", [company]);
    await assert.rejects(read(), /MODULE_DISABLED/); await assert.rejects(save(crypto.randomUUID(), null, values), /MODULE_DISABLED/);
    await db.query("select set_company_module($1,'revenue',true)", [company]); assert.deepEqual(await read(), data);
    for (const table of ["revenue_entries", "revenue_changes"]) {
      for (const statement of [`select * from ${table}`, `delete from ${table}`, `update ${table} set company_id='${companies[1]}'`, `insert into ${table}(company_id) values('${company}')`]) await assert.rejects(db.query(statement), /permission denied/);
    }
    await signIn(users[1]);
    await assert.rejects(read(), /ACCESS_DENIED/); await assert.rejects(save(ids[0], 1, values), /ACCESS_DENIED/);
    await db.query("select set_company_module($1,'revenue',true)", [companies[1]]);
    assert.deepEqual(await read(companies[1]), { entries: [] });
    const foreign = await save(ids[0], null, { ...values, cash: 999 }, companies[1]);
    assert.equal(foreign.entries.length, 1, "entry IDs cannot cross tenant scope");
    await db.exec("reset role"); await db.query("insert into memberships(company_id,user_id,role) values($1,$2,'manager')", [company, users[1]]);
    await signIn(users[1]);
    data = await save(ids[0], 1, { ...values, cash: 1, cards: 2 }); assert.equal(data.entries.find(e => e.id === ids[0])!.version, 2);
    await db.exec("reset role"); await db.query("delete from memberships where company_id=$1 and user_id=$2", [company, users[1]]);
    await signIn(users[1]); await assert.rejects(read(), /ACCESS_DENIED/); await assert.rejects(save(ids[0], 2, values), /ACCESS_DENIED/);
    await signIn(users[0]);
    assert.deepEqual(await read(), data);
    const token = (await db.query<{ t: string }>("select rotate_planner_link($1) t", [company])).rows[0].t;
    await db.exec("set role anon"); await db.query("select set_config('request.jwt.claim.sub','',false)");
    await assert.rejects(read(), /permission denied/); await assert.rejects(save(ids[0], 2, values), /permission denied/);
    await assert.rejects(db.query("select private.read_revenue($1)", [company]), /permission denied/);
    const planner = JSON.stringify((await db.query("select read_planner_workspace($1)", [token])).rows);
    for (const secret of ["revenue_entries", ids[0], ids[1], ids[2], "Veče", "3075"]) assert.ok(!planner.includes(secret));
    await db.exec("reset role");
    const changes = (await db.query<{ n: number }>("select count(*)::integer n from revenue_changes where company_id=$1", [company])).rows[0].n;
    assert.equal(changes, 5, "audit has only successful creates/edits, no duplicate retries");
    await db.query("update companies set access_status='expired' where id=$1", [company]);
    await signIn(users[0]); assert.deepEqual(await read(), data);
    await assert.rejects(save(crypto.randomUUID(), null, values), /TRIAL_EXPIRED/);
    await db.exec("reset role"); await db.query("update companies set access_status='pilot',trial_ends_at=null where id=$1", [company]);
    await signIn(users[0]); await save(crypto.randomUUID(), null, { ...values, date: "2026-03-29", cash: 0 });
    // All public financial APIs are invoker wrappers; no data grants even to members.
    await db.exec("reset role");
    const wrappers = (await db.query<{ prosecdef: boolean }>("select prosecdef from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname in ('read_revenue','save_revenue')")).rows;
    assert.equal(wrappers.length, 2); assert.ok(wrappers.every(p => !p.prosecdef));
  } finally { await db.close(); }
});
